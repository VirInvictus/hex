#!/usr/bin/env python3
"""Convert tt_dw's map/mdt_adverbs.tin into Hex's committed MDT word data.

Dev-time tool (stdlib only): parses the read-only tt_dw clone and emits
src/hex_mdtdata.lua — the 16 mdt colours and the ~960-entry adverb
alternation used by the written-map people tracker's cleanup pass
(docs/phase-5-room.md §2). The data is COMMITTED (like hex_spelldata.lua)
so /add_plugin installs work without a tt_dw clone.

The adverb string ships verbatim (pipe-joined entries, bracket-aware split,
$mtdt colours kept as literal placeholders) — hex_mdt.lua expands the seven
pattern forms at load time. Validation: exactly 16 colours; every entry
non-empty; entry count stable against the source.

Usage: python3 tools/convert_mdtdata.py [--adverbs PATH] [--out PATH]
"""

import argparse
import os
import re

DEFAULT_SRC = os.path.expanduser("~/.gitrepos/tt_dw/scripts/map/mdt_adverbs.tin")
DEFAULT_OUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "src",
    "hex_mdtdata.lua",
)

HEADER = """\
-- hex_mdtdata.lua: MDT word data, GENERATED by tools/convert_mdtdata.py
-- from the read-only tt_dw clone (scripts/map/mdt_adverbs.tin, public
-- domain). Do not hand-edit; regenerate instead. hex_mdt.lua splits the
-- adverb alternation bracket-aware and expands its pattern forms.
--
-- $mdt_colors inside the adverbs is a literal placeholder for the colour
-- list below, exactly as the tin source writes it.
"""


def split_top_level(body):
    """Split on '|' at paren depth 0 (tt_dw entries never nest braces here)."""
    entries = []
    depth = 0
    cur = ""
    for ch in body:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "|" and depth == 0:
            entries.append(cur)
            cur = ""
        else:
            cur += ch
    entries.append(cur)
    return [e for e in entries if e]


def parse_source(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    colours = []
    m = re.search(r"#var mdt_colors \{([^}]*)\};", text)
    if m:
        colours = split_top_level(m.group(1))
    for m in re.finditer(r"#cat mdt_colors \{([^}]*)\};", text):
        colours.extend(split_top_level(m.group(1)))
    entries = []
    for m in re.finditer(r"#(?:var|cat) a \{([^}]*(?:\{[^}]*\}[^}]*)*)\};", text):
        entries.extend(split_top_level(m.group(1)))
    return colours, entries


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--adverbs", default=DEFAULT_SRC, help="mdt_adverbs.tin path")
    ap.add_argument("--out", default=DEFAULT_OUT, help="output lua path")
    args = ap.parse_args()

    colours, entries = parse_source(args.adverbs)
    if len(colours) != 16:
        raise SystemExit(f"expected 16 mdt colours, got {len(colours)}: {colours}")
    if not entries:
        raise SystemExit("no adverb entries parsed")
    for e in entries:
        if not e.strip():
            raise SystemExit("empty adverb entry")

    lines = [
        HEADER,
        "local M = {}",
        "",
        f"M.colors = {{ {', '.join(lua_str(c) for c in colours)} }}",
        "",
    ]
    lines.append("-- the full adverb alternation, verbatim (pipe-joined).")
    lines.append(f"-- entries: {len(entries)}")
    lines.append("M.adverbs = " + lua_str("|".join(entries)))
    lines.append("")
    lines.append("return M")
    lines.append("")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {args.out}: {len(colours)} colours, {len(entries)} adverb entries")


if __name__ == "__main__":
    main()
